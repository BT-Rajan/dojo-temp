"""
Generates apps/website/static/website/css/tokens.css from the Elite Academy design system's
tokens.json (apps/website/design/tokens.json, copied from the Claude Design system).

    python scripts/build_design_tokens.py

Never edit tokens.css by hand: change the design system, copy its tokens.json here, re-run.
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "apps/website/design/tokens.json"
OUT = ROOT / "apps/website/static/website/css/tokens.css"

# Values the reference build uses that are not separate tokens in the design system.
# Each is derived from a token (named in the comment) so there are no stray hex values in the CSS.
DERIVED = {
    "light": {
        "eyebrow-on-deep": "#f6a95a",  # orange-text (dark value): eyebrows on surface-deep
        "logo-plate": "#ffffff",  # the logo's white plate on every ground (brand book: Logo)
        "photo-deep": "#33404a",  # placeholder ground for photos on deep bands
        "spine-rail": "#d9d2c8",  # the vertical belt spine on the home page
        "viewer-ground": "#0b0f12",  # near-black photo viewer ground
        "viewer-ink": "#f4f1ec",  # on-deep, used on the viewer
        "online-dot": "#5cc98a",  # success (dark value): SAQR "online" dot on the night-blue header
    },
}


def resolve(value, theme, table):
    match = re.fullmatch(r"\{([A-Za-z0-9_.-]+)\}", value.strip())
    if match:
        return resolve(table[match.group(1)][theme], theme, table)
    return value


def main():
    data = json.loads(SRC.read_text())
    themes = [t["id"] for t in data["color"]["themes"]]
    table = {}
    for tok in data["color"]["tokens"]:
        value = tok["value"]
        table[tok["name"]] = value if isinstance(value, dict) else {themes[0]: value}
    for per_theme in table.values():
        for theme in themes:
            per_theme.setdefault(theme, per_theme[themes[0]])

    lines = ["/* GENERATED by scripts/build_design_tokens.py from tokens.json — do not edit. */", ":root {"]
    for name in table:
        lines.append(f"  --{name}: {resolve(table[name][themes[0]], themes[0], table)};")
    for family in ("spacing", "radius", "size"):
        for tok in data.get(family, {}).get("tokens", []):
            lines.append(f"  --{tok['name']}: {tok['value']};")
    for tok in data.get("shadow", {}).get("tokens", []):
        value = tok["value"]
        lines.append(f"  --{tok['name']}: {value['light'] if isinstance(value, dict) else value};")
    for key, family in data["type"]["families"].items():
        lines.append(f"  --font-{key}: {family};")
    for name, value in DERIVED["light"].items():
        lines.append(f"  --{name}: {value};")
    lines.append("}")

    dark = [t for t in themes if t != themes[0]]
    for theme in dark:
        lines.append(f'[data-theme="{theme}"] {{')
        lines.append("  color-scheme: dark;")
        for name in table:
            light_v = resolve(table[name][themes[0]], themes[0], table)
            dark_v = resolve(table[name][theme], theme, table)
            if dark_v != light_v:
                lines.append(f"  --{name}: {dark_v};")
        for tok in data.get("shadow", {}).get("tokens", []):
            value = tok["value"]
            if isinstance(value, dict) and theme in value:
                lines.append(f"  --{tok['name']}: {value[theme]};")
        lines.append("}")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(table)} colour tokens)")


if __name__ == "__main__":
    main()
